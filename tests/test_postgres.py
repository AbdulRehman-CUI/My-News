"""Offline PostgreSQL contracts plus optional disposable-database integration."""
import os
import unittest
import uuid
import json
from unittest.mock import Mock, patch

from app import create_app
from storage import PostgresDatabase, _postgres_sql, transaction


class PostgresContractTests(unittest.TestCase):
    def test_json_timestamp_normalization_includes_ingestion_report(self):
        from datetime import datetime, timezone
        row = PostgresDatabase._normalize({"report": {"new": 2}, "started_at": datetime(2026, 10, 22, tzinfo=timezone.utc)})
        self.assertEqual(json.loads(row["report"]), {"new": 2})
        self.assertEqual(row["started_at"], "2026-10-22T00:00:00Z")

    def test_reads_are_autocommit_and_nested_work_uses_one_transaction(self):
        connection = Mock()
        connection.info.transaction_status = 0
        def execute(sql, _params=()):
            if sql == "BEGIN":
                connection.info.transaction_status = 2
            return Mock()
        connection.execute.side_effect = execute
        with patch("psycopg.connect", return_value=connection) as connect:
            db = PostgresDatabase("postgresql://test-only")
        self.assertTrue(connect.call_args.kwargs["autocommit"])
        with transaction(db):
            with transaction(db):
                db.execute("SELECT ?", (1,))
        self.assertEqual(connection.commit.call_count, 1)
        self.assertEqual([call.args[0] for call in connection.execute.call_args_list].count("BEGIN"), 1)
        self.assertEqual(_postgres_sql("BEGIN IMMEDIATE"), "BEGIN")


@unittest.skipUnless(os.environ.get("MYNEWS_TEST_DATABASE_URL"), "MYNEWS_TEST_DATABASE_URL is not configured")
class PostgresIntegrationTests(unittest.TestCase):
    """Use only an explicit disposable database, never the production URL."""
    def setUp(self):
        from psycopg.conninfo import make_conninfo
        self.schema = "mynews_test_" + uuid.uuid4().hex
        self.admin = PostgresDatabase(os.environ["MYNEWS_TEST_DATABASE_URL"])
        self.addCleanup(self.admin.close)
        self.admin.execute(f'CREATE SCHEMA "{self.schema}"')
        # Only the schema generated by this test is removed, even on setup failure.
        self.addCleanup(lambda: self.admin.execute(f'DROP SCHEMA "{self.schema}" CASCADE'))
        self.url = make_conninfo(os.environ["MYNEWS_TEST_DATABASE_URL"], options=f"-c search_path={self.schema}")
        self.app = create_app({"TESTING": True, "DATABASE_URL": self.url, "SECRET_KEY": "postgres-test"})
        self.db = PostgresDatabase(self.url)
        self.addCleanup(self.db.close)
        self.prefs = {"interests": ["Technology"], "timezone": "Asia/Karachi"}
        for reader_id in (1, 2):
            self.db.execute("INSERT INTO readers(id,display_name,onboarding_complete) VALUES(?,?,1)", (reader_id, "Test"))
            self.db.execute("INSERT INTO preferences(reader_id,data) VALUES(?,?)", (reader_id, json.dumps(self.prefs)))

    def populate(self, db=None, session=None):
        from news import canonical_url, ingest
        rss = b'<rss version="2.0"><channel><item><title>Technology report</title><link>https://news.example/pg-story</link><description>Enough feed reporting to be useful without optional neural models or extraction.</description></item></channel></rss>'
        response = Mock(status_code=200)
        response.iter_content.return_value = [rss]
        session = session or Mock()
        if session.get.side_effect is None:
            session.get.return_value = response
        with patch("news.safe_public_url", side_effect=canonical_url):
            return ingest(db or self.db, session=session, feeds={"https://feed.example/rss": ["Technology"]})

    def test_postgres_recovery_preservation_and_portable_queries(self):
        from editions import archive, edition_items, generate_edition, set_progress, set_saved
        from news import ingestion_diagnostics, remaining_budget
        first = generate_edition(self.db, 1, self.prefs)
        self.assertEqual(first["status"], "empty")
        self.assertEqual(self.populate().new, 1)
        self.assertEqual(self.populate().duplicate, 1)
        ready = generate_edition(self.db, 1, self.prefs)
        self.assertEqual(ready["id"], first["id"])
        item = edition_items(self.db, ready["id"], 1)[0]
        set_saved(self.db, 1, item["article_id"], ready["id"], True)
        set_progress(self.db, 1, ready["id"], item["id"], True)
        self.assertEqual(edition_items(self.db, ready["id"], 1)[0]["completed"], 1)
        self.assertEqual(len(archive(self.db, 1, ready["local_date"])), 1)
        with self.assertRaises(ValueError):
            set_saved(self.db, 2, item["article_id"], ready["id"], True)
        self.assertEqual(dict(generate_edition(self.db, 1, self.prefs)), dict(ready))
        self.assertEqual(ingestion_diagnostics(self.db)["eligible_article_count"], 1)
        self.assertEqual(remaining_budget(self.db), 80)

    def test_postgres_concurrent_ingestion_and_generation(self):
        import threading
        from concurrent.futures import ThreadPoolExecutor
        from editions import edition_items, generate_edition
        entered, release = threading.Event(), threading.Event()
        def fetch(*_args, **_kwargs):
            entered.set()
            release.wait(5)
            result = Mock(status_code=200)
            result.iter_content.return_value = [b'<rss version="2.0"><channel><item><title>Technology news</title><link>https://news.example/concurrent</link><description>Long enough technology feed text for this concurrent production pipeline test.</description></item></channel></rss>']
            return result
        def refresh():
            db = PostgresDatabase(self.url)
            try:
                return self.populate(db, Mock(get=Mock(side_effect=fetch)))
            finally:
                db.close()
        with ThreadPoolExecutor(max_workers=2) as pool:
            future = pool.submit(refresh)
            self.assertTrue(entered.wait(5))
            try:
                self.assertEqual(self.populate().status, "busy")
                empty = generate_edition(self.db, 1, self.prefs)
                self.assertEqual(empty["status"], "empty")
            finally:
                release.set()
            self.assertEqual(future.result(timeout=10).new, 1)
            barrier = threading.Barrier(2)
            def generate():
                db = PostgresDatabase(self.url)
                try:
                    barrier.wait(timeout=5)
                    return dict(generate_edition(db, 1, self.prefs))
                finally:
                    db.close()
            futures = [pool.submit(generate) for _ in range(2)]
            editions = [job.result(timeout=10) for job in futures]
        self.assertEqual(editions[0], editions[1])
        self.assertEqual(editions[0]["id"], empty["id"])
        self.assertEqual(len(edition_items(self.db, empty["id"], 1)), 1)
